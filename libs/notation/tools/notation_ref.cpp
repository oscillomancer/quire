#include <supple/notation/notation.h>

#include "internal.h"

#include <array>
#include <cstdint>
#include <cstdlib>
#include <iostream>
#include <string>
#include <string_view>

namespace {

void example(std::string_view title, std::string_view source) {
    const auto compiled = supple::notation::compile(source);
    if (!compiled) {
        std::cerr << compiled.error().toString() << '\n';
        std::exit(1);
    }
    const auto canonical = supple::notation::decompile(compiled->sequence);
    if (!canonical) {
        std::cerr << canonical.error().toString() << '\n';
        std::exit(1);
    }
    std::cout << "### " << title << "\n\nInput:\n\n```text\n"
              << source << "```\n\nCanonical decompile:\n\n```text\n"
              << *canonical << "```\n\n";
}

}  // namespace

int main() {
    using namespace supple::notation::internal;
    std::cout << "# Notation reference\n\n"
              << "Generated by `notation-ref` from the notation compiler's tables and "
                 "compiled examples. Regenerate with `tools/gen/update-generated.sh`.\n\n"
              << "A single numbered bar can use the implicit `voice main`. Bars sum to "
                 "the meter; `|` continues the next bar without another number, though "
                 "`| N:` is also accepted when N is that bar. "
                 "The default is 4/4 at 960 ticks per quarter note.\n\n"
              << "## Durations\n\n| Token | Ticks at PPQ 960 |\n|---|---:|\n";
    for (std::string_view token :
         std::array<std::string_view, 16>{"w", "h", "q", "e", "s", "t", "x", "q.", "q..", "e3",
                                          "s5", "s6", "s7", "e9", "h+e", "700t"}) {
        bool fraction = false;
        const auto ticks = duration(token, 960, fraction);
        if (!ticks && !fraction) return 1;
        std::cout << "| `" << token << "` | ";
        if (ticks)
            std::cout << *ticks;
        else
            std::cout << "fractional";
        std::cout << " |\n";
    }
    std::cout << "\nDots: `q.` and `q..`. Tuplets use a suffix: `e3`, `s5`, `s6`, "
                 "`s7`, `e9`. Add durations with `+` (`h+e`) or use exact ticks "
                 "(`700t`). A rest is `r:DUR`; `r:*` fills the bar.\n\n"
              << "## Articulations\n\n| Suffix | Effect |\n|---|---|\n"
              << "| `" << kStaccato << "` | Half note length, minimum one tick |\n"
              << "| `" << kAccent << "` | Add 20 velocity, maximum 127 |\n\n"
              << "A trailing `~` ties matching adjacent notes; `&` layers a note "
                 "without advancing the bar cursor.\n\n"
              << "## Dynamics and velocity\n\n| Word | Velocity |\n|---|---:|\n";
    for (const auto& [word, velocity] : dynamics())
        std::cout << "| `" << word << "` | " << velocity << " |\n";
    std::cout << "\nThe default velocity is 96. `:NN` sets note-on velocity; "
                 "`:NN/MM` also sets note-off velocity.\n\n"
              << "## Chord qualities\n\nChord symbols use `{Cquality}:DUR` "
                 "(root octave 3 by default). A slash bass such as `{C/E}` sits "
                 "one octave below the root.\n\n"
              << "| Symbol | Semitone intervals |\n|---|---|\n";
    for (const auto& [quality, intervals] : chordQualities()) {
        std::cout << "| `{C" << quality << "}` |";
        for (int interval : intervals) std::cout << ' ' << interval;
        std::cout << " |\n";
    }
    std::cout << "\n## General MIDI drum names\n\n"
              << "Use these in a `voice drums ch 10 grid s` section. `n36` also "
                 "names MIDI note 36.\n\n"
              << "| Name | MIDI note |\n|---|---:|\n";
    for (const auto& [name, pitch] : gmDrums())
        std::cout << "| `" << name << "` | " << static_cast<int>(pitch) << " |\n";
    std::cout << "\n## Named controllers\n\n| Name | CC |\n|---|---:|\n";
    for (const auto& [name, number] : ccNames())
        std::cout << "| `" << name << "` | " << number << " |\n";
    std::cout << "\n## Worked examples\n\n";
    example("Implicit melody", "notation 1\n1: C4:q E4:q G4:h\n");
    example("Chord and dynamics", "notation 1\nvoice keys vel 80\n1: mp {Cm7}:h {G7}:h\n");
    example("Drum grid", "notation 1\nvoice drums ch 10 grid q\n1: kick x...\n1: clap .x.x\n");
    example("Controller lane", "notation 1\nlane cc cutoff\n1.1 20\n1.3 90\n");
}
